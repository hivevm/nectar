//! The format-neutral document model.

use std::collections::BTreeMap;
use std::path::PathBuf;

use crate::config::Split;
use crate::diagnostic::Origin;

/// A complete document, built from one start document and everything it includes.
#[derive(Debug, Clone)]
pub struct Document {
    pub title: String,
    /// Output directory of the document, relative to the output root.
    pub path: String,
    pub split: Split,
    /// Whether headings carry section numbers.
    pub numbered: bool,
    /// Whether the document starts with a table of contents of the whole document.
    pub contents: bool,
    /// Settings of the print renderer from `[document.print]`, read by that renderer.
    pub print: toml::Table,
    pub root: Chapter,
    /// Footnotes of the whole document, ordered by number.
    pub footnotes: Vec<Footnote>,
    /// Local files the document refers to: source path to output path, both relative.
    pub assets: BTreeMap<PathBuf, PathBuf>,
    /// The content of assets that are no project files, such as downloaded images, by their
    /// source path in `assets`.
    pub downloads: BTreeMap<PathBuf, Vec<u8>>,
}

/// The content of one source file. The start document is the root chapter; every include adds a
/// nested chapter.
#[derive(Debug, Clone, Default)]
pub struct Chapter {
    pub id: String,
    /// Path segment of the chapter's page when the document is split.
    pub slug: String,
    pub title: String,
    /// Source file, relative to the project root.
    pub source: PathBuf,
    pub blocks: Vec<Block>,
    /// Footnote definitions of this file. The footnote pass moves them to the document.
    pub footnotes: Vec<FootnoteDefinition>,
}

#[derive(Debug, Clone)]
pub struct Block {
    pub origin: Origin,
    pub kind: BlockKind,
}

#[derive(Debug, Clone)]
pub enum BlockKind {
    Chapter(Chapter),
    Heading(Heading),
    Paragraph(Vec<Inline>),
    Quote(Vec<Block>),
    Alert(AlertKind, Vec<Block>),
    List(List),
    Table(Table),
    ThematicBreak,
    Code(Code),
    HighlightedCode(HighlightedCode),
    Graphic(Graphic),
    /// A block with a caption, such as a file embedded through an image link.
    Figure(String, Box<Block>),
    /// Raw HTML written by the author.
    Html(String),
}

#[derive(Debug, Clone)]
pub struct Heading {
    pub level: u8,
    /// Set by `{#id}` or by the id pass.
    pub id: String,
    /// Section number such as `1.2.`, set by the numbering pass; empty when unnumbered.
    pub number: String,
    pub content: Vec<Inline>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AlertKind {
    Note,
    Success,
    Warning,
    Error,
}

#[derive(Debug, Clone)]
pub struct List {
    pub ordered: bool,
    pub start: usize,
    pub tight: bool,
    pub items: Vec<ListItem>,
}

#[derive(Debug, Clone)]
pub struct ListItem {
    /// `Some(checked)` for a task list item.
    pub task: Option<bool>,
    pub blocks: Vec<Block>,
}

#[derive(Debug, Clone)]
pub struct Table {
    pub columns: Vec<Column>,
    pub header: Vec<Vec<Inline>>,
    pub rows: Vec<Vec<Vec<Inline>>>,
}

#[derive(Debug, Clone, Copy)]
pub struct Column {
    pub align: Align,
    /// Relative width: the number of `-` in the column's delimiter cell.
    pub width: u32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Align {
    Auto,
    Left,
    Center,
    Right,
}

/// A code block no engine has handled.
#[derive(Debug, Clone)]
pub struct Code {
    pub language: String,
    pub code: String,
}

/// Code split into lines of styled tokens by a highlighting engine.
#[derive(Debug, Clone, PartialEq)]
pub struct HighlightedCode {
    pub language: String,
    pub foreground: Option<String>,
    pub background: Option<String>,
    pub lines: Vec<Vec<Token>>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub text: String,
    pub style: TokenStyle,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct TokenStyle {
    /// Colour as `#rrggbb` or `#rrggbbaa`.
    pub color: Option<String>,
    pub background: Option<String>,
    pub bold: bool,
    pub italic: bool,
    pub underline: bool,
    pub strikethrough: bool,
}

/// A picture generated by a diagram engine.
#[derive(Debug, Clone, PartialEq)]
pub struct Graphic {
    pub language: String,
    pub svg: String,
    pub alt: String,
    /// The code the picture was generated from.
    pub code: String,
}

#[derive(Debug, Clone)]
pub enum Inline {
    Text(String),
    Emphasis(Vec<Inline>),
    Strong(Vec<Inline>),
    Highlight(Vec<Inline>),
    Strikethrough(Vec<Inline>),
    Underline(Vec<Inline>),
    Code(String),
    Link(Link),
    Image(Image),
    /// Reference to a footnote; the footnote pass sets the number.
    FootnoteRef {
        label: String,
        number: usize,
    },
    /// A named glyph of the theme's symbol font.
    Symbol(String),
    SoftBreak,
    LineBreak,
    /// Raw HTML written by the author.
    Html(String),
}

#[derive(Debug, Clone)]
pub struct Link {
    pub target: Target,
    pub title: String,
    pub content: Vec<Inline>,
    /// Written as a reference link, `[text][id]`; such links to external targets become
    /// footnotes.
    pub reference: bool,
    /// Number of the footnote that shows the target, set by the footnote pass; 0 for none.
    pub footnote: usize,
}

#[derive(Debug, Clone)]
pub struct Image {
    pub target: Target,
    pub title: String,
    pub alt: String,
    pub attributes: Vec<(String, String)>,
}

/// Where a link or image points to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Target {
    /// A URL outside the project, kept as written.
    External(String),
    /// A heading or chapter id in the document. Before the link pass it holds the fragment as
    /// written.
    Anchor(String),
    /// A Markdown file, relative to the project root, with an optional fragment. The link pass
    /// turns it into an anchor when the file is part of the document.
    File {
        path: PathBuf,
        fragment: Option<String>,
    },
    /// Any other local file, relative to the project root.
    Asset(PathBuf),
}

#[derive(Debug, Clone)]
pub struct FootnoteDefinition {
    pub label: String,
    pub blocks: Vec<Block>,
}

#[derive(Debug, Clone)]
pub struct Footnote {
    pub number: usize,
    pub blocks: Vec<Block>,
}

impl Inline {
    /// The text of an inline sequence without any markup.
    pub fn plain_text(inlines: &[Inline]) -> String {
        let mut text = String::new();
        for inline in inlines {
            inline.push_plain_text(&mut text);
        }
        text
    }

    fn push_plain_text(&self, text: &mut String) {
        match self {
            Inline::Text(value) | Inline::Code(value) => text.push_str(value),
            Inline::Emphasis(children)
            | Inline::Strong(children)
            | Inline::Highlight(children)
            | Inline::Strikethrough(children)
            | Inline::Underline(children) => children.iter().for_each(|c| c.push_plain_text(text)),
            Inline::Link(link) => link.content.iter().for_each(|c| c.push_plain_text(text)),
            Inline::Image(image) => text.push_str(&image.alt),
            Inline::SoftBreak | Inline::LineBreak => text.push(' '),
            Inline::FootnoteRef { .. } | Inline::Symbol(_) | Inline::Html(_) => {}
        }
    }
}

/// Calls `f` for every block, depth first, including blocks of nested chapters.
pub fn visit_blocks_mut(blocks: &mut [Block], f: &mut dyn FnMut(&mut Block)) {
    for block in blocks {
        f(block);
        match &mut block.kind {
            BlockKind::Chapter(chapter) => visit_blocks_mut(&mut chapter.blocks, f),
            BlockKind::Quote(children) | BlockKind::Alert(_, children) => {
                visit_blocks_mut(children, f)
            }
            BlockKind::Figure(_, inner) => visit_blocks_mut(std::slice::from_mut(inner), f),
            BlockKind::List(list) => {
                for item in &mut list.items {
                    visit_blocks_mut(&mut item.blocks, f);
                }
            }
            _ => {}
        }
    }
}

/// Calls `f` for the chapter and every nested chapter, in document order.
pub fn visit_chapters_mut(chapter: &mut Chapter, f: &mut dyn FnMut(&mut Chapter)) {
    f(chapter);
    for block in &mut chapter.blocks {
        if let BlockKind::Chapter(child) = &mut block.kind {
            visit_chapters_mut(child, f);
        }
    }
}

/// Calls `f` for every inline sequence directly held by a block (not those of nested blocks).
pub fn block_inlines_mut(block: &mut Block, f: &mut dyn FnMut(&mut Vec<Inline>)) {
    match &mut block.kind {
        BlockKind::Paragraph(inlines) => f(inlines),
        BlockKind::Heading(heading) => f(&mut heading.content),
        BlockKind::Table(table) => {
            table.header.iter_mut().for_each(&mut *f);
            for row in &mut table.rows {
                row.iter_mut().for_each(&mut *f);
            }
        }
        _ => {}
    }
}

/// Calls `f` for every inline in the sequence, depth first.
pub fn visit_inlines_mut(inlines: &mut [Inline], f: &mut dyn FnMut(&mut Inline)) {
    for inline in inlines {
        f(inline);
        match inline {
            Inline::Emphasis(children)
            | Inline::Strong(children)
            | Inline::Highlight(children)
            | Inline::Strikethrough(children)
            | Inline::Underline(children) => visit_inlines_mut(children, f),
            Inline::Link(link) => visit_inlines_mut(&mut link.content, f),
            _ => {}
        }
    }
}
